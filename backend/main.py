@app.post("/api/v1/simulate", response_model=SimulateResponse)
def simulate(req: SimulateRequest):
    """
    Run a what-if scenario. Currently uses the Phase 1 baseline formula
    (confirmed in Phase 1 testing to outperform a trained model on the
    available 21-event dataset) -- see PHASE1_SUMMARY.md for why.
    """
    predicted_pct = req.supply_loss_pct / ELASTICITY

    # Plain-language explanation, built from what Phase 1 actually found --
    # not a generic message. This is where the "explanation" part of your
    # dashboard goal comes from.
    parts = []
    if req.supply_loss_pct > 0:
        parts.append(f"A {req.supply_loss_pct:.1f}% loss of global supply, under standard "
                      f"short-run demand inelasticity (Ed = -{ELASTICITY}), implies roughly a "
                      f"{predicted_pct:.1f}% price increase.")
    elif req.supply_loss_pct < 0:
        parts.append(f"A {abs(req.supply_loss_pct):.1f}% increase in supply implies roughly a "
                      f"{abs(predicted_pct):.1f}% price decrease.")
    else:
        parts.append("No direct supply change specified.")

    if req.demand_change_pct != 0:
        parts.append(f"Note: this scenario also involves a {req.demand_change_pct:.1f}% demand "
                      f"change. Phase 1 testing found demand-driven events (like 2020 COVID or "
                      f"2008) behave differently from pure supply shocks, and this formula does "
                      f"not yet account for that -- treat this prediction as less reliable when "
                      f"demand_change_pct is far from zero.")

    if req.conflict_intensity >= 7 and req.supply_loss_pct < 2:
        parts.append(f"Conflict intensity is high ({req.conflict_intensity}) but modeled supply "
                      f"loss is low -- historically (e.g. the 2025 Israel-Iran war), this pattern "
                      f"produces a real but short-lived price spike that fades once markets "
                      f"confirm no physical disruption occurred.")

    # Independently of the crude-price formula above: the news pipeline's
    # lithium_supply_index (news/price_engine.py, nudged by classified
    # ev_lithium_supply events) feeds straight into this EV feasibility
    # calculation, the exact same way chokepoint_disruption events feed
    # the simulated crude price -- see ev_lithium.py's docstring for the
    # index's meaning. Defaults to 1.0 (no-op) until a real/fixture
    # ev_lithium_supply event has actually fired.
    lithium_supply_index = price_engine.get_state()["lithium_supply_index"]
    ev = supply_shock_to_ev_feasibility(req.supply_loss_pct, lithium_supply_index=lithium_supply_index)

    return SimulateResponse(
        predicted_price_change_pct=round(predicted_pct, 2),
        explanation=" ".join(parts),
        model_used="elasticity_formula_baseline",
        ev_feasibility=EvFeasibility(
            barrels_per_day_lost=round(ev.barrels_per_day_lost, 0),
            gasoline_vehicle_years_displaced=round(ev.equivalent.gasoline_vehicle_years_displaced, 0),
            lithium_tonnes_required=round(ev.equivalent.lithium_tonnes_required, 0),
            lithium_supply_ratio=round(ev.lithium_supply_ratio, 3),
            explanation=ev.explanation,
        ),
    )


def _chokepoint_coords_for(chokepoint: str) -> dict:
    return CHOKEPOINT_COORDS.get(str(chokepoint).lower(), {"lat": None, "lng": None})


def _price_event_to_conflict_event(row: dict) -> ConflictEvent:
    """Reshapes one news-pipeline price_events row into the SAME
    ConflictEvent schema the static events.csv rows use (project brief
    section 5: reuse the existing event schema, don't create a second,
    parallel history store). conflict_intensity and supply_loss_pct are
    DERIVED, not independently chosen -- supply_loss_pct is backed out of
    the actual simulated price move via the same ELASTICITY the rest of
    this app already uses (predicted_pct = supply_loss_pct / ELASTICITY,
    inverted here), so this stays internally consistent with /api/v1/simulate
    rather than inventing a third, disconnected scale."""
    chokepoints = json.loads(row["chokepoints_json"])
    chokepoint = chokepoints[0] if chokepoints else "none"
    coords = _chokepoint_coords_for(chokepoint)

    pct_change = row["price_pct_change"] or 0.0
    supply_loss_pct = round(pct_change * ELASTICITY, 2)
    conflict_intensity = round(max(0.0, min(10.0, abs(row["severity"]) * row["confidence"] * 12)), 1)

    return ConflictEvent(
        name=f"{row['summary']} [SIMULATED, {row['classifier_used']}]",
        event_date=row["occurred_at"][:10],
        chokepoint=chokepoint,
        conflict_intensity=conflict_intensity,
        supply_loss_pct=supply_loss_pct,
        lat=coords["lat"],
        lng=coords["lng"],
    )


@app.get("/api/v1/conflicts", response_model=list[ConflictEvent])
def get_conflicts():
    """Returns all historical events with coordinates where available --
    the static dataset (events.csv) UNIONED with live, news-driven events
    that actually moved the simulated crude price (news/price_engine.py).
    Live entries are clearly tagged '[SIMULATED, <classifier>]' in their
    name so they're never mistaken for the real historical record."""
    results = []
    for _, row in events_df.iterrows():
        coords = _chokepoint_coords_for(row["chokepoint"])
        results.append(ConflictEvent(
            name=row["name"],
            event_date=row["event_date"].strftime("%Y-%m-%d"),
            chokepoint=row["chokepoint"],
            conflict_intensity=row["conflict_intensity"],
            supply_loss_pct=row["supply_loss_pct"],
            lat=coords["lat"],
            lng=coords["lng"],
        ))

    for row in news_db.crude_price_events_for_chart():
        results.append(_price_event_to_conflict_event(row))

    return results


@app.get("/api/v1/refineries", response_model=list[RefineryHub])
def get_refineries():
    """Returns all refinery/export-hub locations and capacities for the globe."""
    return [
        RefineryHub(
            name=row["name"],
            country=row["country"],
            lat=row["lat"],
            lng=row["lng"],
            capacity_bpd=row["capacity_bpd"],
            hub_type=row["hub_type"],
            nearest_chokepoint=row["nearest_chokepoint"],
            notes=row["notes"],
        )
        for _, row in refineries_df.iterrows()
    ]


@app.get("/api/v1/refineries/at-risk/{chokepoint}", response_model=ChokepointRisk)
def get_chokepoint_risk(chokepoint: str):
    """
    Total refining/export capacity dependent on one chokepoint (Hormuz,
    Suez, Malacca, Bab el-Mandeb) -- e.g. if Hormuz were blockaded, this
    is how much capacity, and which named hubs, would be cut off.
    """
    if chokepoint.lower() not in KNOWN_CHOKEPOINTS:
        raise HTTPException(status_code=404, detail=f"Unknown chokepoint '{chokepoint}'. Known: {sorted(KNOWN_CHOKEPOINTS)}")

    at_risk_df = refineries_at_chokepoint(refineries_df, chokepoint)
    capacity = capacity_at_risk_bpd(refineries_df, chokepoint)
    pct = capacity_at_risk_pct_of_global(refineries_df, chokepoint, DEFAULT_GLOBAL_DAILY_CRUDE_PRODUCTION_BBL)

    return ChokepointRisk(
        chokepoint=chokepoint,
        capacity_at_risk_bpd=round(capacity, 0),
        pct_of_global_daily_production=round(pct, 4),
        affected_hubs=list(at_risk_df["name"]),
    )


@app.get("/api/v1/routes/{chokepoint}", response_model=RouteRecommendation)
def get_route_recommendation(chokepoint: str):
    """
    Documented bypass routes for one chokepoint (real pipelines like
    Petroline/ADCOP/SUMED, or alternate straits like Lombok/Sunda), and how
    much of that chokepoint's at-risk capacity they can actually absorb vs
    what's left with only the slow Cape-of-Good-Hope option. See
    routing.py's KNOWN SIMPLIFICATION note: bypass capacity is pooled per
    chokepoint, not matched to which specific hub's crude it serves.
    """
    if chokepoint.lower() not in KNOWN_CHOKEPOINTS:
        raise HTTPException(status_code=404, detail=f"Unknown chokepoint '{chokepoint}'. Known: {sorted(KNOWN_CHOKEPOINTS)}")

    result = recommend_reroute(refineries_df, bypass_routes_df, chokepoint)

    return RouteRecommendation(
        chokepoint=result.chokepoint,
        capacity_at_risk_bpd=round(result.capacity_at_risk_bpd, 0),
        affected_hubs=result.affected_hubs,
        bypass_options=[
            BypassOption(
                via=o.via,
                route_type=o.route_type,
                capacity_bpd=o.capacity_bpd,
                extra_transit_days=o.extra_transit_days,
                notes=o.notes,
            )
            for o in result.bypass_options
        ],
        fast_bypass_capacity_bpd=round(result.fast_bypass_capacity_bpd, 0),
        uncovered_capacity_bpd=round(result.uncovered_capacity_bpd, 0),
        explanation=result.explanation,
    )


# ---------------------------------------------------------------------------
# News pipeline: ingestion -> classification (Claude when ANTHROPIC_API_KEY
# is set, else a rule-based fallback -- see news/classify.py) -> price
# simulation (news/price_engine.py) -> alert feed / historical chart union.
# The poller runs automatically via the lifespan handler above; these
# endpoints expose the resulting state and a manual test-injection path.
# ---------------------------------------------------------------------------
class TestInjectRequest(BaseModel):
    """Either set fixture_key (see news/fixtures.py for the available
    keys), or provide title/description/url directly for a one-off
    hand-written test article."""

    fixture_key: str | None = None
    title: str | None = None
    description: str | None = None
    url: str | None = None
    source: str = "manual-test"


class TestInjectResponse(BaseModel):
    article_title: str
    relevant: bool
    classifier_used: str | None = None
    classification: ClassifiedEvent | None = None
    skipped_reason: str | None = None
    price_state: dict | None = None


@app.post("/api/v1/news/test-inject", response_model=TestInjectResponse)
def test_inject_news(req: TestInjectRequest):
    """
    DEV-ONLY manual test-injection path (project brief section 6): feeds a
    fixture or hand-written article straight into the relevance ->
    classification -> price-engine pipeline, so the whole flow can be
    verified without waiting for real news. Not meant to be exposed
    outside local development.
    """
    if req.fixture_key:
        if req.fixture_key not in FIXTURES:
            raise HTTPException(status_code=404, detail=f"Unknown fixture_key. Known: {sorted(FIXTURES)}")
        article = FIXTURES[req.fixture_key]
    elif req.title and req.description and req.url:
        article = Article(title=req.title, description=req.description, url=req.url, source=req.source, published_at="")
    else:
        raise HTTPException(status_code=400, detail="Provide either fixture_key or title+description+url")

    if not is_relevant(article.title, article.description):
        news_db.record_skipped(url_hash(article.url), article, reason="skipped_not_relevant")
        return TestInjectResponse(article_title=article.title, relevant=False, skipped_reason="skipped_not_relevant")

    try:
        event, classifier_used = classify_article(article)
    except Exception as e:
        # e.g. the Claude path is active but the Anthropic API itself is
        # down/erroring -- a clear 503 beats an opaque 500.
        raise HTTPException(status_code=503, detail=str(e))

    news_db.record_classification(url_hash(article.url), article, event, classifier_used)
    price_state = price_engine.apply_event(article, event, classifier_used)

    return TestInjectResponse(
        article_title=article.title,
        relevant=True,
        classifier_used=classifier_used,
        classification=event,
        price_state=price_state,
    )


