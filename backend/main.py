# ---------------------------------------------------------------------------
# Request / response schemas
# Pydantic (the library these classes use) automatically validates incoming
# JSON against these definitions -- if a request is missing a field or sends
# a string where a number is expected, FastAPI rejects it automatically,
# before your code even runs.
# ---------------------------------------------------------------------------
class SimulateRequest(BaseModel):
    supply_loss_pct: float = Field(..., ge=-20, le=20, description="Percent of global crude supply lost (negative = surplus added)")
    conflict_intensity: float = Field(..., ge=0, le=10, description="0 (none) to 10 (full-scale war)")
    detour_days: float = Field(0, ge=0, description="Extra shipping days from rerouting, if applicable")
    demand_change_pct: float = Field(0, ge=-50, le=50, description="Percent change in global demand (negative = demand drop)")


class EvFeasibility(BaseModel):
    barrels_per_day_lost: float
    gasoline_vehicle_years_displaced: float
    lithium_tonnes_required: float
    lithium_supply_ratio: float = Field(
        ..., description="lithium_tonnes_required / one year of global lithium production"
    )
    explanation: str


class SimulateResponse(BaseModel):
    predicted_price_change_pct: float
    explanation: str
    model_used: str
    ev_feasibility: EvFeasibility


class ConflictEvent(BaseModel):
    name: str
    event_date: str
    chokepoint: str
    conflict_intensity: float
    supply_loss_pct: float
    lat: float | None = None
    lng: float | None = None


class RefineryHub(BaseModel):
    name: str
    country: str
    lat: float
    lng: float
    capacity_bpd: float
    hub_type: str
    nearest_chokepoint: str
    notes: str


class ChokepointRisk(BaseModel):
    chokepoint: str
    capacity_at_risk_bpd: float
    pct_of_global_daily_production: float
    affected_hubs: list[str]


class BypassOption(BaseModel):
    via: str
    route_type: str
    capacity_bpd: float | None
    extra_transit_days: float
    notes: str


class RouteRecommendation(BaseModel):
    chokepoint: str
    capacity_at_risk_bpd: float
    affected_hubs: list[str]
    bypass_options: list[BypassOption]
    fast_bypass_capacity_bpd: float
    uncovered_capacity_bpd: float
    explanation: str


