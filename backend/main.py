@app.get("/api/v1/news/price")
def get_simulated_price():
    """Current simulated crude price + EV/lithium supply index. ALWAYS a
    simulation calibrated off classified news, never a live market quote
    -- see news/price_engine.py's docstring."""
    state = price_engine.get_state()
    return {**state, "is_simulation": True}


@app.get("/api/v1/news/alerts")
def get_news_alerts(limit: int = 50):
    """Live alert feed data: every event that actually moved the
    simulated price or lithium index, newest first."""
    return news_db.recent_price_events(limit=limit)


