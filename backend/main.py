"""
Phase 2: FastAPI backend for the oil crisis simulation platform.

Endpoints, matching the original project spec plus the refinery/GIS layer:
    POST /api/v1/simulate                    -- run a what-if crisis scenario,
                                                  get a predicted price change,
                                                  EV/lithium feasibility, and a
                                                  plain-language explanation
    GET  /api/v1/conflicts                    -- list historical events with
                                                  coordinates, for the globe
    GET  /api/v1/refineries                   -- list refinery/export hubs
                                                  with coordinates + capacity,
                                                  for the globe
    GET  /api/v1/refineries/at-risk/{chokepoint} -- capacity dependent on one
                                                  chokepoint (Hormuz, Suez,
                                                  Malacca, Bab el-Mandeb)
    GET  /api/v1/routes/{chokepoint}          -- bypass routes for one
                                                  chokepoint (real pipelines/
                                                  alternate straits), and how
                                                  much at-risk capacity they
                                                  can actually absorb

Run this with:  uvicorn main:app --reload
Then open:      http://127.0.0.1:8000/docs
(that /docs page is auto-generated by FastAPI -- it gives you a free
interactive UI to test both endpoints without writing any frontend code yet)
"""

